<?php

/**
 * CSRF Protection Tests
 *
 * Laravel's PreventRequestForgery (VerifyCsrfToken) middleware unconditionally
 * skips token verification when the application detects it is "running unit
 * tests" (runningInConsole() && runningUnitTests()).  It is therefore not
 * possible to trigger a real HTTP 419 response from the Artisan test runner;
 * any attempt to do so will simply pass through.
 *
 * Instead, these tests confirm CSRF protection is in place by verifying:
 *
 *  1. The global middleware stack applies PreventRequestForgery to all web
 *     routes (and correctly excludes api/*).
 *  2. Every page that makes or receives mutating requests renders a CSRF token
 *     — either via the Blade @csrf directive (forms) or the meta[name="csrf-token"]
 *     tag (AJAX pages).
 *  3. Authenticated JSON endpoints reject callers that are not authenticated
 *     (guards the critical /web/* surface).
 *  4. Public routes that mutate state (login, register) reject obviously bad
 *     input with validation errors — not silently accepting forged requests.
 */

use App\Models\User;

// ─────────────────────────────────────────────────────────────────────────────
// 1.  Middleware registration
// ─────────────────────────────────────────────────────────────────────────────

test('bootstrap registers PreventRequestForgery on the web middleware stack', function () {
    $kernel    = app(\Illuminate\Foundation\Http\Kernel::class);
    $webMiddleware = collect($kernel->getMiddlewareGroups()['web'] ?? []);

    // The web group must include the CSRF middleware (under either alias).
    $hasCsrf = $webMiddleware->contains(fn ($m) =>
        in_array($m, [
            \Illuminate\Foundation\Http\Middleware\PreventRequestForgery::class,
            \Illuminate\Foundation\Http\Middleware\VerifyCsrfToken::class,
        ], true)
    );

    expect($hasCsrf)->toBeTrue('PreventRequestForgery must be in the web middleware group');
})->skip(fn () => ! method_exists(app(\Illuminate\Foundation\Http\Kernel::class), 'getMiddlewareGroups'), 'Kernel::getMiddlewareGroups not available');

test('the CSRF middleware excludes api/* routes and only api/* routes', function () {
    // Read the bootstrap/app.php exclusion list via the configured middleware.
    // We instantiate the middleware and call its getExcludedPaths() helper.
    $middleware = app(\Illuminate\Foundation\Http\Middleware\PreventRequestForgery::class);
    $excluded   = $middleware->getExcludedPaths();

    // api/* must be excluded (mobile clients use Sanctum bearer tokens).
    expect($excluded)->toContain('api/*');

    // Sensitive web paths must NOT be excluded.
    $sensitiveRoutes = ['/login', '/register', '/logout', '/profile', '/settings', '/web/*'];
    foreach ($sensitiveRoutes as $route) {
        expect($excluded)->not->toContain($route, "Route '{$route}' must not be CSRF-excluded");
    }
});

// ─────────────────────────────────────────────────────────────────────────────
// 2.  CSRF token present in every view that mutates state
// ─────────────────────────────────────────────────────────────────────────────

test('the login page renders a csrf-token meta tag and a hidden _token field', function () {
    $response = $this->get('/login')->assertOk();

    // Meta tag for JS use.
    $response->assertSee('<meta name="csrf-token"', false);
    // Hidden input generated by @csrf directive.
    $response->assertSee('name="_token"', false);
});

test('the register page renders a csrf-token meta tag and a hidden _token field', function () {
    $response = $this->get('/register')->assertOk();

    $response->assertSee('<meta name="csrf-token"', false);
    $response->assertSee('name="_token"', false);
});

test('the dashboard renders a csrf-token meta tag', function () {
    $user = User::factory()->create();

    $this->actingAs($user)
        ->get(route('dashboard'))
        ->assertOk()
        ->assertSee('<meta name="csrf-token"', false);
});

test('the integrations hub renders a csrf-token meta tag and uses X-CSRF-TOKEN in AJAX', function () {
    $user = User::factory()->create();

    $response = $this->actingAs($user)
        ->get(route('integrations'))
        ->assertOk();

    $response->assertSee('<meta name="csrf-token"', false);
    // The JS helper must read from the meta tag.
    $response->assertSee("'X-CSRF-TOKEN'", false);
});

test('the gate page renders a csrf-token meta tag and uses X-CSRF-TOKEN in AJAX', function () {
    $user        = User::factory()->create();
    $integration = $user->integrations()->create([
        'name'       => 'Target App',
        'url'        => 'https://target.example/login',
        'secret_key' => 'TESTSECRETKEY1234',
        'is_active'  => true,
    ]);

    $response = $this->get("/i/{$integration->gate_token}")->assertOk();

    $response->assertSee('<meta name="csrf-token"', false);
    $response->assertSee("'X-CSRF-TOKEN'", false);
});

test('the profile page renders a csrf-token meta tag and hidden _token fields', function () {
    $user = User::factory()->create();

    $response = $this->actingAs($user)
        ->get(route('profile'))
        ->assertOk();

    $response->assertSee('<meta name="csrf-token"', false);
    // Multiple @csrf forms on the page.
    $response->assertSee('name="_token"', false);
});

test('the settings page renders a csrf-token meta tag and a hidden _token field', function () {
    $user = User::factory()->create();

    $response = $this->actingAs($user)
        ->get(route('settings'))
        ->assertOk();

    $response->assertSee('<meta name="csrf-token"', false);
    $response->assertSee('name="_token"', false);
});

test('the logout form in the profile menu renders a hidden _token field', function () {
    $user = User::factory()->create();

    // The profile-menu partial is included on every authenticated page.
    $this->actingAs($user)
        ->get(route('dashboard'))
        ->assertOk()
        ->assertSee('name="_token"', false);
});

// ─────────────────────────────────────────────────────────────────────────────
// 3.  Authentication guards the /web/* JSON surface
//     (unauthenticated calls are already blocked before CSRF even matters)
// ─────────────────────────────────────────────────────────────────────────────

test('unauthenticated POST to /web/integrations returns 401 or redirects to login', function () {
    $this->postJson('/web/integrations', [
        'name' => 'Evil App',
        'url'  => 'https://evil.example/login',
    ])->assertUnauthorized();
});

test('unauthenticated DELETE to /web/integrations/1 returns 401', function () {
    $this->deleteJson('/web/integrations/1')
        ->assertUnauthorized();
});

test('unauthenticated PATCH to /web/integrations/1/toggle returns 401', function () {
    $this->patchJson('/web/integrations/1/toggle')
        ->assertUnauthorized();
});

test('unauthenticated PATCH to /web/login-events/1/archive returns 401', function () {
    $this->patchJson('/web/login-events/1/archive')
        ->assertUnauthorized();
});

test('unauthenticated DELETE to /web/login-events/1 returns 401', function () {
    $this->deleteJson('/web/login-events/1')
        ->assertUnauthorized();
});

// ─────────────────────────────────────────────────────────────────────────────
// 4.  API routes correctly bypass CSRF (Sanctum bearer token auth)
// ─────────────────────────────────────────────────────────────────────────────

test('POST /api/mobile/login is CSRF-exempt and returns a validation error, not 419', function () {
    // If CSRF were enforced here this would fail at the middleware level (419),
    // not reach validation.  A 422 confirms the request made it to the controller.
    $this->postJson('/api/mobile/login', [
        'email'    => 'nobody@example.com',
        'password' => 'wrongpassword',
    ])->assertStatus(422);
});
